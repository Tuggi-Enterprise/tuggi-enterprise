test.describe("DS-COMPONENTE-051 / 052 — the listing and its card", () => {
  test("DS-COMPONENTE-052: the order is strictly descending by date, ties on the slug", () => {
    for (const locale of LOCALES) {
      const listing = listUpdates(locale);
      const sorted = [...listing].sort((a, b) =>
        a.publishedAt === b.publishedAt
          ? a.slug.localeCompare(b.slug)
          : b.publishedAt.localeCompare(a.publishedAt)
      );
      expect(listing.map((d) => d.slug), `${locale} is out of order`).toEqual(
        sorted.map((d) => d.slug)
      );

      // The other half of DS-COMPONENTE-052, and it is a trip-wire rather than
      // a property: while the section holds up to 24 pieces the listing is one
      // complete page. Above that it has to paginate BY ROUTE — one indexable
      // URL per page, with rel=next/prev — never infinite scroll and never a
      // "load more" with no URL, because content behind infinite scroll is not
      // crawled reliably. This goes red on the 25th article, which is when the
      // card is due.
      expect(
        listing.length,
        `${locale} crossed ${LISTING_CEILING} articles — the route-anchored pagination of ` +
          "DS-COMPONENTE-052 is now due"
      ).toBeLessThanOrEqual(LISTING_CEILING);
    }
  });

  test("DS-COMPONENTE-053: below the floor there is no filter control in the DOM", async ({
    page,
  }) => {
    // The floor is per locale, because the listing is per locale: 12 articles
    // AND at least 3 of each type. A control for a list that fits in one glance
    // is furniture. When a locale crosses the floor this goes red, which is the
    // trip-wire that opens the card.
    for (const locale of LOCALES) {
      const listing = listUpdates(locale);
      expect(
        showsTypeFilter(listing),
        `${locale} has ${listing.length} articles and crossed the floor of ` +
          `${FILTER_FLOOR.articles}/${FILTER_FLOOR.perType} — the filter of DS-COMPONENTE-053 is now due`
      ).toBe(false);

      await page.goto(sectionUrl(locale));
      await expect(
        page.locator('[data-block="update-type-filter"]'),
        `${locale} renders a filter the floor does not allow`
      ).toHaveCount(0);
    }
  });

  for (const [width, columns] of [
    [1280, 3],
    [700, 2],
    [360, 1],
  ] as const) {
    test(`DS-COMPONENTE-051: the grid has ${columns} column(s) at ${width} px, and no card under 300 px`, async ({
      page,
    }) => {
      await page.setViewportSize({ width, height: 900 });
      await page.goto(sectionUrl(DEFAULT_LOCALE));

      const grid = page.locator("main div.grid").first();
      const measured = await grid.evaluate((node) => ({
        columns: getComputedStyle(node).gridTemplateColumns.split(" ").filter(Boolean).length,
        cardWidths: [...node.children].map((child) => child.getBoundingClientRect().width),
      }));

      // Three and not four, measured: at 1280 the rail gives 1216 px, and with
      // gap-6 three columns are 389 px — where the clamped summary breaks at
      // ~48 characters. Four give 286 px and three lines become a fragment.
      expect(measured.columns, `${width} px`).toBe(columns);
      for (const cardWidth of measured.cardWidths) {
        expect(cardWidth, `a card measures ${cardWidth} px at ${width} px`).toBeGreaterThanOrEqual(
          300
        );
      }
    });
  }

  for (const locale of LOCALES) {
    test(`DS-COMPONENTE-051: on ${locale} every card is one tab stop named by its title`, async ({
      page,
    }) => {
      await page.setViewportSize({ width: 1280, height: 900 });
      await page.goto(sectionUrl(locale));

      const listing = listUpdates(locale);
      for (const document of listing) {
        const card = page.locator(`main a[href="${articleUrl(document)}"]`);
        // One target per card: the affordance is not a second anchor, because
        // two links to one destination are two keyboard stops for one decision.
        await expect(card, `${document.slug} is linked more than once`).toHaveCount(1);

        // NOT toHaveAccessibleName: whitespace between inline children makes
        // that matcher normalise a real difference away. The name is anchored
        // on the h2 by aria-labelledby, so the h2's text IS the name.
        const labelledBy = await card.getAttribute("aria-labelledby");
        expect(labelledBy, "the card composes its name out of everything inside it").toBeTruthy();
        const name = await page.locator(`#${labelledBy}`).evaluate((node) => node.textContent ?? "");
        expect(name.trim()).toBe(document.title);
      }
    });

    test(`DS-COMPONENTE-051: on ${locale} the cards of a row are the same height`, async ({
      page,
    }) => {
      await page.setViewportSize({ width: 1280, height: 900 });
      await page.goto(sectionUrl(locale));

      const heights = await page
        .locator("main div.grid > a")
        .evaluateAll((nodes) =>
          nodes.map((node) => Math.round(node.getBoundingClientRect().height))
        );
      expect(heights.length).toBeGreaterThan(0);
      expect(new Set(heights).size, `card heights in ${locale}: ${heights.join(", ")}`).toBe(1);
    });
  }

  test("DS-COPY-047: the empty state of a locale with no article is translated", () => {
    // Every locale publishes the first article today, so the empty state has no
    // page to be measured on. What CAN go wrong without anybody noticing is a
    // missing translation, which next-intl publishes as the key name — and that
    // is what this checks. The rendered state joins the day a locale is behind.
    for (const locale of LOCALES) {
      const messages = JSON.parse(
        fs.readFileSync(path.join(REPO_ROOT, "src/messages", `${locale}.json`), "utf8")
      );
      for (const key of ["body", "link"] as const) {
        const value = messages.Updates?.empty?.[key];
        expect(value, `Updates.empty.${key} is missing from ${locale}.json`).toBeTruthy();
        expect(value, `Updates.empty.${key} renders its own name in ${locale}`).not.toContain(
          "Updates.empty"
        );
      }
    }
  });
});

