test.describe("Routes — the section and the article answer at the translated slug", () => {
  for (const locale of LOCALES) {
    test(`DS-COPY-006: /${locale}${localizedPathname(locale, UPDATES_SECTION)} answers 200`, async ({
      request,
    }) => {
      const response = await request.get(sectionUrl(locale), { maxRedirects: 0 });
      expect(response.status(), `${sectionUrl(locale)} is the declared slug of ${locale}`).toBe(200);
    });

    test(`DS-COMPONENTE-057: every article of ${locale} answers at its own leaf`, async ({
      request,
    }) => {
      const listing = listUpdates(locale);
      expect(listing.length, `${locale} publishes no article; the section has nothing to prove`)
        .toBeGreaterThan(0);

      for (const document of listing) {
        const response = await request.get(articleUrl(document), { maxRedirects: 0 });
        expect(response.status(), articleUrl(document)).toBe(200);
      }
    });
  }

  test("DS-COMPONENTE-057: the leaf of ANOTHER language does not serve the piece", async ({
    request,
  }) => {
    // THE FAILURE THIS EXISTS FOR. `localizedPathname` translates the ancestor
    // and carries the leaf through, so `/pt/novidades/hour-passes` is exactly
    // what a hreflang built by string concatenation would publish. It has to be
    // a 404 and not a page: an address that answers 200 in two languages is two
    // canonical URLs for one piece.
    const foreign: string[] = [];
    for (const article of getUpdateArticles()) {
      const leaves = slugsByLocale(article.id);
      for (const locale of LOCALES) {
        const own = leaves[locale];
        for (const [otherLocale, otherLeaf] of Object.entries(leaves)) {
          if (otherLocale === locale || otherLeaf === own) continue;
          foreign.push(`${sectionUrl(locale)}/${otherLeaf}`);
        }
      }
    }
    expect(foreign.length, "no article has two different leaves to cross").toBeGreaterThan(0);

    for (const url of foreign) {
      const response = await request.get(url, { maxRedirects: 0 });
      expect(response.status(), `${url} serves a piece at an address nothing links to`).toBe(404);
    }
  });

  test("DS-COPY-006: the untranslated section word never serves a second copy", async ({
    request,
  }) => {
    // `/pt/updates` is the internal pathname under a locale that translates it.
    // next-intl answers a redirect to the canonical `/pt/novidades` rather than
    // a 404 — which is the behaviour we want and NOT what the spec's criterion
    // 1 predicted. What matters is the same either way: the internal word never
    // answers 200 with a second copy of the page.
    for (const locale of LOCALES) {
      const internal = `/${locale}${UPDATES_SECTION}`;
      if (internal === sectionUrl(locale)) continue;
      const response = await request.get(internal, { maxRedirects: 0 });
      expect([301, 302, 307, 308, 404], `${internal} answered ${response.status()}`).toContain(
        response.status()
      );
    }
  });
});

