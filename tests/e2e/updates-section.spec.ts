test.describe("DS-COPY-046 / DS-A11Y-011 — what the content files may contain", () => {
  test("DS-A11Y-011: no `#` opens a line in any body", () => {
    for (const { file, raw } of contentFiles()) {
      const body = raw.replace(/^---\n[\s\S]*?\n---\n/, "");
      const offenders = body
        .split("\n")
        .map((line, index) => ({ line: index + 1, text: line }))
        .filter(({ text }) => /^#(?!#)/.test(text))
        .map(({ line, text }) => `${file}:${line}: ${text}`);
      expect(offenders, "the `h1` belongs to the template").toEqual([]);
    }
  });

  test("DS-COPY-046: asides are counted per paragraph, with a ceiling per piece", () => {
    // The unit is the paragraph, because an article has no i18n key. The four
    // marks count TOGETHER — a guard matching only `[—–]` passes green in
    // Spanish, which translates the same asides with a colon.
    for (const { file, raw } of contentFiles()) {
      const { blocks } = parseEditorialDocument(raw, file);
      const paragraphs = blocks
        .filter((block) => block.kind === "paragraph")
        .map((block) =>
          block.kind === "paragraph"
            ? block.children
                .map((node) => (node.kind === "text" ? node.value : ""))
                .join("")
            : ""
        );

      expect(paragraphs.length, `${file} has no paragraph to measure`).toBeGreaterThan(0);

      const withAside = paragraphs.filter((text) => asideMarks(text) > 0);
      for (const text of paragraphs) {
        expect(asideMarks(text), `${file}: "${text.slice(0, 70)}"`).toBeLessThanOrEqual(
          ASIDE_CEILING
        );
        expect(longestBreath(text), `${file}: "${text.slice(0, 70)}"`).toBeLessThanOrEqual(
          BREATH_CEILING
        );
      }
      expect(
        withAside.length * 3,
        `${file}: ${withAside.length} of ${paragraphs.length} paragraphs carry an aside`
      ).toBeLessThanOrEqual(paragraphs.length);
    }
  });

  test("DS-COMPONENTE-054: an unknown tag, a style or a className is a parse error", () => {
    const frontmatter = [
      "---",
      "slug: x",
      "title: T",
      "summary: S",
      "type: news",
      "publishedAt: 2026-01-01",
      "cover: generated",
      "ogAlt: A",
      "---",
      "",
    ].join("\n");

    const refused: [string, string][] = [
      ["an undeclared component", '<ArticleCarousel src="a" />'],
      ["an inline style", '<ArticleNotice body="a" style="color:red" />'],
      ["a utility class", '<ArticleNotice body="a" className="text-red-500" />'],
      ["a figure with no alt", '<ArticleFigure src="/a.png" />'],
      ["an anonymous quotation", '<ArticleQuote quote="a" />'],
      ["a blank cell in before/after", '<ArticleChangeTable caption="c" beforeLabel="b" afterLabel="a" rows={[["x", ""]]} />'],
      ["an `h1` in the body", "# a heading the template owns"],
      ["an `h3` with no `h2` above it", "### orphan"],
    ];

    for (const [why, body] of refused) {
      expect(
        () => parseEditorialDocument(frontmatter + body + "\n", "<test>"),
        `${why} was accepted`
      ).toThrow();
    }
  });

  test("DS-COPY-048: a waiver with no reason is refused, and one with a reason is kept", () => {
    const base = [
      "---",
      "slug: x",
      "title: T",
      "summary: S",
      "type: news",
      "publishedAt: 2026-01-01",
      "cover: generated",
      "ogAlt: A",
    ].join("\n");

    const withReason = parseEditorialDocument(
      `${base}\nwaiver:\n  - rule: ACCESS_IN_DAYS\n    reason: "BR-MONETIZACAO-062 — the piece explains the extinction"\n---\n\nA paragraph.\n`,
      "<test>"
    );
    expect(withReason.frontmatter.waiver).toEqual([
      {
        rule: "ACCESS_IN_DAYS",
        reason: "BR-MONETIZACAO-062 — the piece explains the extinction",
      },
    ]);
  });

  test("TEMPORARY: the article #1 is still marked as provisional", () => {
    // The body of the first article is placeholder text on purpose: the copy is
    // the `design`'s and lands in the next round. This assertion is the guard
    // against the failure mode that has burned other teams — placeholder that
    // reads like real copy gets published and nobody notices.
    //
    // WHEN THE REAL COPY LANDS, THIS TEST IS DELETED IN THE SAME COMMIT. It is
    // not a rule; it is a marker with a deadline, and it goes red the moment
    // somebody half-replaces the text.
    const markers = /TEXTO PROVISÓRIO|PLACEHOLDER TEXT|TEXTO PROVISIONAL|TESTO PROVVISORIO/;
    for (const { file, raw } of contentFiles()) {
      expect(raw, `${file} no longer declares itself provisional`).toMatch(markers);
    }
  });
});
