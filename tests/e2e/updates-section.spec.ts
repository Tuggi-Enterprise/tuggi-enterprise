/**
 * The editorial section of the site — news and release notes.
 *
 * Spec: `docs/design/spec-secao-novidades-site-2026-08.md`.
 *
 * The rules this file proves, and the reason each one is here rather than
 * anywhere else:
 *
 * `DS-COMPONENTE-057` — a route whose **leaf** is translated builds hreflang,
 *   canonical and sitemap from the registry that knows the slug of each locale,
 *   never by handing one string to `buildAlternates`. This is the expensive
 *   one: `localizedPathname` already translates the ancestor, so
 *   `/updates/hour-passes` becomes `/novidades/hour-passes` — the right prefix
 *   with the wrong leaf, a URL that 404s, published as the Portuguese
 *   alternate of all four language versions at once. It looks correct in a
 *   quick inspection, which is exactly why it needs a test and not a reading.
 * `DS-COMPONENTE-051` / `052` / `053` — the card, the order, and the floor the
 *   type filter does not exist below.
 * `DS-COMPONENTE-054` / `055` / `056` / `058` — the closed block set, the
 *   before/after table, the share card generated by route, and the single CTA.
 * `DS-LAYOUT-011` / `012` — the section is in the footer and not in the menu;
 *   the reading column has a measured ceiling.
 * `DS-A11Y-011` — the heading structure belongs to the template.
 * `DS-COPY-046` / `047` / `048` — asides by paragraph, the four locales as one
 *   piece, and the catalogue guard reaching editorial content.
 * `BR-COMUNICACAO-009` — this is the first surface of ours that **dates** an
 *   assertion, so the date has to be machine-readable and identical in the four
 *   languages of one piece.
 * `BR-COMUNICACAO-010` — the ceiling on what may be asserted about the hour
 *   model. The mechanical half is here: no amount is born in an article, and no
 *   article sells access by the day without a declared dispensation.
 *
 * ---------------------------------------------------------------------------
 * Two things this file does NOT do
 * ---------------------------------------------------------------------------
 *
 * 1. **It never reads `page.content()`.** next-intl ships every source string
 *    of every page inside the RSC payload, so the raw HTML of any page contains
 *    the sentence a guard is asserting is absent. `publishedText` strips the
 *    scripts; see `support/published-text.ts`.
 * 2. **It never asserts an accessible name with `toHaveAccessibleName`.** With
 *    whitespace between inline children the matcher normalises the difference
 *    away and passes on a name the browser composes differently. The card's
 *    name is anchored on the `h2` through `aria-labelledby`, and the assertion
 *    reads `textContent`.
 */

const REPO_ROOT = path.resolve(__dirname, "../..");
const CONTENT_DIR = path.join(REPO_ROOT, "src/content/updates");

/** The listing of one locale, as a URL. */
function sectionUrl(locale: string): string {
  return `/${locale}${localizedPathname(locale, UPDATES_SECTION)}`;
}

/** The article of one locale, as a URL — from the registry, never composed. */
function articleUrl(document: UpdateDocument): string {
  return `${sectionUrl(document.locale)}/${document.slug}`;
}

/** Every `.mdx` of the section, with its path relative to the repo root. */
function contentFiles(): { file: string; raw: string }[] {
  if (!fs.existsSync(CONTENT_DIR)) return [];
  return fs
    .readdirSync(CONTENT_DIR)
    .flatMap((id) => {
      const dir = path.join(CONTENT_DIR, id);
      if (!fs.statSync(dir).isDirectory()) return [];
      return fs
        .readdirSync(dir)
        .filter((name) => name.endsWith(".mdx"))
        .map((name) => ({
          file: path.relative(REPO_ROOT, path.join(dir, name)),
          raw: fs.readFileSync(path.join(dir, name), "utf8"),
        }));
    });
}

/** Answers /api/geo with a country, before anything on the page asks —
 *  the same double `base-market-price.spec.ts` uses. */
async function geoAnswers(page: Page, country: string | null): Promise<void> {
  await page.route("**/api/geo", (route: Route) =>
    route.fulfill({
      status: 200,
      contentType: "application/json",
      body: JSON.stringify({ country }),
    })
  );
}

