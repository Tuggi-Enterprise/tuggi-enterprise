test.describe("DS-COMPONENTE-057 — hreflang of an article comes from the registry", () => {
  for (const locale of LOCALES) {
    test(`DS-COMPONENTE-057: hreflang on ${locale} names each locale's own leaf`, async ({
      request,
    }) => {
      for (const document of listUpdates(locale)) {
        const response = await request.get(articleUrl(document));
        expect(response.status()).toBe(200);
        const html = await response.text();

        const alternates = Object.fromEntries(
          [
            ...html.matchAll(/<link rel="alternate" hrefLang="([^"]+)" href="([^"]+)"/g),
          ].map((match) => [match[1], new URL(match[2]).pathname])
        );

        const leaves = slugsByLocale(document.id);
        const expected: Record<string, string> = {};
        for (const [other, leaf] of Object.entries(leaves)) {
          expected[other] = `${sectionUrl(other)}/${leaf}`;
        }
        // DS-COPY-047: only the locales the piece exists in. Pointing at a
        // translation that is not there is how all four are lost at once.
        expected["x-default"] = expected[DEFAULT_LOCALE] ?? Object.values(expected)[0];

        expect(alternates, `hreflang on ${articleUrl(document)}`).toEqual(expected);

        // And every address it names resolves.
        for (const href of new Set(Object.values(alternates))) {
          const alternate = await request.get(href, { maxRedirects: 0 });
          expect(alternate.status(), `alternate ${href}`).toBe(200);
        }
      }
    });

    test(`DS-COMPONENTE-056: og:image is the route, and og:image:alt is in ${locale}`, async ({
      page,
    }) => {
      for (const document of listUpdates(locale)) {
        await page.goto(articleUrl(document));

        const image = await page
          .locator('meta[property="og:image"]')
          .first()
          .getAttribute("content");
        // The INTERNAL path: the generated route is
        // `[locale]/updates/[slug]/opengraph-image`, and the localized pattern
        // `/novidades/[slug]` matches one segment, not two.
        expect(image, "og:image does not point at this article's own card").toContain(
          `/${locale}${UPDATES_SECTION}/${document.slug}/opengraph-image`
        );

        const alt = await page
          .locator('meta[property="og:image:alt"]')
          .first()
          .getAttribute("content");
        // The `alt` export of an opengraph-image is static and never sees
        // `params` — this is the whole reason the page keeps `openGraph.images`
        // instead of letting the file convention take over.
        expect(alt, "og:image:alt is not this locale's").toBe(document.ogAlt);
      }
    });

    test(`DS-COMPONENTE-056: the ${locale} share card answers 200 at 1200 × 630`, async ({
      request,
    }) => {
      for (const document of listUpdates(locale)) {
        const url = `/${locale}${UPDATES_SECTION}/${document.slug}/opengraph-image`;
        const response = await request.get(url);
        expect(response.status(), url).toBe(200);
        expect(response.headers()["content-type"]).toContain("image/png");

        // The IHDR of a PNG carries the size in bytes 16–23; reading it is
        // cheaper and more honest than trusting the route's `size` export.
        const body = await response.body();
        expect(body.readUInt32BE(16), `${url} width`).toBe(1200);
        expect(body.readUInt32BE(20), `${url} height`).toBe(630);
      }
    });

    test(`the ${locale} <title> does not name the brand twice`, async ({ request }) => {
      // The root layout appends "| TUGGI"; a frontmatter title that names it
      // would publish it twice in the one string a search result shows.
      for (const url of [sectionUrl(locale), ...listUpdates(locale).map(articleUrl)]) {
        const html = await (await request.get(url)).text();
        const title = /<title>([^<]*)<\/title>/.exec(html)?.[1] ?? "";
        expect(title, `${url} has no <title>`).not.toBe("");
        expect(
          (title.match(/TUGGI/gi) ?? []).length,
          `${url} publishes "${title}"`
        ).toBeLessThanOrEqual(1);
      }
    });
  }
});

